import React, { useState } from 'react';
import { useApp } from '../context/AppContext';
import {
  X,
  Palette,
  Sparkles,
  Terminal,
  Coins,
  Play,
  Rocket,
  RefreshCw,
  MessageSquare,
  Users,
  Flame,
  Check,
  ArrowRight,
  TrendingUp,
  Zap,
  Key,
  Cpu,
} from 'lucide-react';
import { formatSol, formatTokens, formatUsd, SOL_USD_RATE } from '../utils/bondingCurve';
import { OPENROUTER_MODELS, formatTokenCount, getOpenRouterModel } from '../utils/openrouter';

export const CreatorStudioModal: React.FC<{ onClose: () => void }> = ({ onClose }) => {
  const {
    wallet,
    pocs,
    setActivePoC,
    iteratePoC,
    claimCreatorRoyalties,
    setIsLaunchModalOpen,
    setIsWalletModalOpen,
    openFuelModal,
    updatePoCOpenRouterModel,
    setCreatorOpenRouterApiKey,
  } = useApp();

  // Find PoCs created by this address/name
  const myCreatedPocs = pocs.filter(
    (p) =>
      p.creator.address === wallet.address ||
      p.creator.name.toLowerCase().includes('elena') ||
      p.creator.name === wallet.name ||
      p.creator.handle.toLowerCase() === wallet.name.toLowerCase()
  );

  const [selectedPocId, setSelectedPocId] = useState<string>(
    myCreatedPocs[0]?.id || pocs[0]?.id || ''
  );
  const [newPromptInput, setNewPromptInput] = useState('');
  const [isIterating, setIsIterating] = useState(false);
  const [iterationSuccess, setIterationSuccess] = useState(false);

  const selectedPoc = pocs.find((p) => p.id === selectedPocId) || myCreatedPocs[0] || pocs[0];

  // Community suggestions from comments
  const communitySuggestions = pocs
    .flatMap((p) =>
      p.comments
        .filter((c) => c.isPromptSuggestion)
        .map((c) => ({ ...c, pocTitle: p.title, pocTicker: p.ticker, targetPocId: p.id }))
    )
    .slice(0, 6);

  const handleIteratePrompt = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!newPromptInput.trim() || !selectedPoc) return;

    setIsIterating(true);
    setIterationSuccess(false);
    try {
      await iteratePoC(selectedPoc.id, newPromptInput.trim());
      setIterationSuccess(true);
      setNewPromptInput('');
      setTimeout(() => setIterationSuccess(false), 4000);
    } catch (err) {
      console.error(err);
    } finally {
      setIsIterating(false);
    }
  };

  const adoptSuggestion = (suggestionText: string, pocId: string) => {
    setSelectedPocId(pocId);
    setNewPromptInput(suggestionText);
  };

  // Total volume generated by creator's PoCs
  const totalCreatorVolumeSol = myCreatedPocs.reduce((acc, p) => acc + p.volume24hSol, 0);

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-4 bg-black/85 backdrop-blur-md overflow-y-auto font-sans">
      <div className="relative w-full max-w-4xl bg-[#0b1017] border border-emerald-500/40 rounded-3xl shadow-2xl p-5 sm:p-6 text-slate-100 flex flex-col max-h-[92vh] overflow-hidden">
        {/* Header with Creator identity */}
        <div className="flex items-center justify-between pb-4 border-b border-slate-800 mb-4">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-2xl bg-emerald-500/10 border border-emerald-500/30 flex items-center justify-center text-emerald-400">
              <Palette className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h2 className="text-base sm:text-lg font-bold text-white font-mono">
                  Punto de Vista del Creador (Creator Studio)
                </h2>
                <span className="text-[10px] font-mono bg-emerald-500/20 text-emerald-300 border border-emerald-500/40 px-2 py-0.5 rounded-full font-bold">
                  STUDIO ACTIVO
                </span>
              </div>
              <p className="text-xs text-slate-400 font-mono">
                {wallet.name} • Gestión de PoCs, cobro de regalías (0.5%) y terminal de prompts con Gemini.
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={() => {
                onClose();
                setIsLaunchModalOpen(true);
              }}
              className="bg-emerald-500 hover:bg-emerald-400 text-black font-extrabold text-xs px-3.5 py-1.5 rounded-xl font-mono flex items-center gap-1.5 transition cursor-pointer"
            >
              <Rocket className="w-3.5 h-3.5 fill-black" />
              <span>Nuevo PoC</span>
            </button>

            <button
              onClick={onClose}
              className="w-8 h-8 rounded-xl bg-slate-900 hover:bg-slate-800 text-slate-400 hover:text-white flex items-center justify-center transition cursor-pointer"
            >
              <X className="w-4 h-4" />
            </button>
          </div>
        </div>

        {/* Creator Royalties & Metrics Banner */}
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-3 mb-5 font-mono">
          {/* Royalties Box */}
          <div className="bg-gradient-to-br from-emerald-950/60 to-slate-900 dark:from-emerald-950/60 dark:to-slate-900 light:from-emerald-50 light:to-white border border-emerald-500/40 dark:border-emerald-500/40 light:border-emerald-200 rounded-2xl p-3.5 flex flex-col justify-between space-y-2">
            <div>
              <span className="text-[10px] text-emerald-400 dark:text-emerald-400 light:text-emerald-700 uppercase font-bold tracking-wider block">
                Regalías Disponibles (0.5%)
              </span>
              <span className="text-xl font-bold text-white dark:text-white light:text-slate-900">
                +{wallet.creatorRoyaltiesSol?.toFixed(3) || '0.000'} SOL
              </span>
              <span className="text-[10px] text-slate-400 dark:text-slate-400 light:text-slate-500 block">
                ≈ {formatUsd((wallet.creatorRoyaltiesSol || 0) * SOL_USD_RATE)}
              </span>
            </div>

            <button
              onClick={claimCreatorRoyalties}
              disabled={(wallet.creatorRoyaltiesSol || 0) <= 0}
              className="w-full py-1.5 rounded-xl bg-emerald-500 hover:bg-emerald-400 text-black font-extrabold text-[11px] transition cursor-pointer disabled:opacity-40"
            >
              Reclamar Regalías
            </button>
          </div>

          {/* OpenRouter AI Token Pool Card */}
          <div className="bg-gradient-to-br from-amber-950/50 to-slate-900 dark:from-amber-950/50 dark:to-slate-900 light:from-amber-50 light:to-white border border-amber-500/40 dark:border-amber-500/40 light:border-amber-200 rounded-2xl p-3.5 flex flex-col justify-between space-y-2">
            <div>
              <span className="text-[10px] text-amber-400 dark:text-amber-400 light:text-amber-700 uppercase font-bold tracking-wider block flex items-center gap-1">
                <Zap className="w-3 h-3 fill-amber-400" />
                <span>Tokens OpenRouter (Fuel)</span>
              </span>
              <span className="text-xl font-bold text-amber-300 dark:text-amber-300 light:text-amber-800">
                {formatTokenCount(selectedPoc?.openRouterFuel?.totalTokensRemaining || 2500000)}
              </span>
              <span className="text-[10px] text-slate-400 dark:text-slate-400 light:text-slate-500 block">
                {selectedPoc?.openRouterFuel?.sponsorsCount || 12} Mecenas de la comunidad
              </span>
            </div>

            <button
              onClick={() => selectedPoc && openFuelModal(selectedPoc)}
              className="w-full py-1.5 rounded-xl bg-amber-400/20 hover:bg-amber-400/30 text-amber-300 dark:text-amber-300 light:text-amber-800 border border-amber-400/40 font-extrabold text-[11px] transition cursor-pointer"
            >
              + Inyectar o Recargar Fuel
            </button>
          </div>

          {/* Volume Generated */}
          <div className="bg-slate-900/80 dark:bg-slate-900/80 light:bg-slate-50 border border-slate-800 dark:border-slate-800 light:border-slate-200 rounded-2xl p-3.5 flex flex-col justify-between">
            <span className="text-[10px] text-slate-400 dark:text-slate-400 light:text-slate-600 uppercase font-bold tracking-wider block">
              Volumen Total Generado
            </span>
            <span className="text-xl font-bold text-cyan-400 dark:text-cyan-400 light:text-cyan-700">
              {formatSol(totalCreatorVolumeSol)} SOL
            </span>
            <span className="text-[10px] text-slate-400 dark:text-slate-400 light:text-slate-500">
              En {myCreatedPocs.length} PoCs activos
            </span>
          </div>

          {/* Graduated PoCs */}
          <div className="bg-slate-900/80 dark:bg-slate-900/80 light:bg-slate-50 border border-slate-800 dark:border-slate-800 light:border-slate-200 rounded-2xl p-3.5 flex flex-col justify-between">
            <span className="text-[10px] text-slate-400 dark:text-slate-400 light:text-slate-600 uppercase font-bold tracking-wider block">
              Graduación a DEX
            </span>
            <span className="text-xl font-bold text-purple-400 dark:text-purple-400 light:text-purple-700">
              {myCreatedPocs.filter((p) => p.bondingCurveProgress >= 100).length} / {myCreatedPocs.length}
            </span>
            <span className="text-[10px] text-slate-400 dark:text-slate-400 light:text-slate-500">
              Graduados a Raydium
            </span>
          </div>
        </div>

        {/* Content Body: Created PoCs + Iteration Terminal */}
        <div className="flex-1 overflow-y-auto space-y-5 min-h-0 pr-1">
          {/* SECTION 1: PROMPT ITERATION TERMINAL */}
          <div className="bg-slate-900/80 border border-slate-800 rounded-2xl p-4 sm:p-5 space-y-4 font-mono">
            <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2">
              <div className="flex items-center gap-2">
                <Terminal className="w-4 h-4 text-emerald-400" />
                <h3 className="text-xs sm:text-sm font-bold text-white uppercase tracking-wider">
                  Terminal de Iteración de Prompts (Gemini Engine)
                </h3>
              </div>
              <span className="text-[11px] text-slate-400">
                Mejora tu código sandbox y despliega una nueva versión on-chain
              </span>
            </div>

            {selectedPoc && (
              <div className="bg-slate-950 p-3 rounded-xl border border-slate-800 flex flex-wrap items-center justify-between gap-3 text-xs">
                <div className="flex items-center gap-2">
                  <span className="text-slate-400">PoC Activo:</span>
                  <select
                    value={selectedPoc.id}
                    onChange={(e) => setSelectedPocId(e.target.value)}
                    className="bg-slate-900 border border-slate-700 text-white font-bold rounded-lg px-2.5 py-1 text-xs focus:outline-none"
                  >
                    {pocs.map((p) => (
                      <option key={p.id} value={p.id}>
                        {p.title} ({p.ticker}) — {p.bondingCurveProgress.toFixed(1)}% Curva
                      </option>
                    ))}
                  </select>
                </div>

                <div className="flex items-center gap-2">
                  <span className="text-emerald-400 font-bold">
                    Versión Actual: {selectedPoc.promptHistory[selectedPoc.promptHistory.length - 1]?.version || 'v1.0'}
                  </span>
                  <button
                    type="button"
                    onClick={() => {
                      setActivePoC(selectedPoc);
                      onClose();
                    }}
                    className="px-2.5 py-1 bg-slate-800 hover:bg-slate-700 text-white text-[11px] rounded-lg flex items-center gap-1"
                  >
                    <Play className="w-3 h-3 fill-current" />
                    <span>Ver Sandbox</span>
                  </button>
                </div>
              </div>
            )}

            <form onSubmit={handleIteratePrompt} className="space-y-3">
              <div>
                <label className="text-slate-400 text-xs block mb-1">
                  Especificación de la Nueva Iteración (Prompt Upgrade):
                </label>
                <textarea
                  rows={3}
                  required
                  placeholder="Ej. Añadir modo oscuro con gradiente cyberpunk, soporte de visualización de gráficos en tiempo real y botón de exportar datos en JSON..."
                  value={newPromptInput}
                  onChange={(e) => setNewPromptInput(e.target.value)}
                  className="w-full bg-slate-950 border border-slate-800 rounded-xl p-3 text-white placeholder-slate-600 focus:outline-none focus:border-emerald-500 text-xs font-mono"
                />
              </div>

              {iterationSuccess && (
                <div className="p-3 bg-emerald-950/60 border border-emerald-500/50 rounded-xl text-emerald-300 text-xs flex items-center gap-2">
                  <Check className="w-4 h-4 text-emerald-400" />
                  <span>¡Nueva versión sintetizada con Gemini y desplegada con éxito!</span>
                </div>
              )}

              <button
                type="submit"
                disabled={isIterating || !newPromptInput.trim()}
                className="w-full py-2.5 rounded-xl bg-gradient-to-r from-emerald-500 to-cyan-500 hover:from-emerald-400 hover:to-cyan-400 text-black font-extrabold text-xs transition shadow-lg shadow-emerald-500/20 flex items-center justify-center gap-2 cursor-pointer disabled:opacity-40"
              >
                {isIterating ? (
                  <>
                    <RefreshCw className="w-4 h-4 animate-spin text-black" />
                    <span>Gemini Sintetizando Nuevo Sandbox HTML...</span>
                  </>
                ) : (
                  <>
                    <Sparkles className="w-4 h-4 fill-black" />
                    <span>Desplegar Nueva Versión del PoC</span>
                  </>
                )}
              </button>
            </form>
          </div>

          {/* SECTION 2: COMMUNITY SUGGESTIONS */}
          {communitySuggestions.length > 0 && (
            <div className="space-y-3 font-mono text-xs">
              <h4 className="text-slate-400 uppercase font-semibold text-xs flex items-center gap-2">
                <MessageSquare className="w-4 h-4 text-cyan-400" />
                <span>Sugerencias de Prompts de la Comunidad</span>
              </h4>

              <div className="grid grid-cols-1 sm:grid-cols-2 gap-2.5">
                {communitySuggestions.map((item) => (
                  <div
                    key={item.id}
                    className="bg-slate-950/80 border border-slate-800 p-3 rounded-xl flex flex-col justify-between space-y-2"
                  >
                    <div>
                      <div className="flex items-center justify-between text-[11px] mb-1">
                        <span className="text-cyan-400 font-bold">{item.pocTicker}</span>
                        <span className="text-slate-500">{item.user.name}</span>
                      </div>
                      <p className="text-slate-300 font-sans text-xs line-clamp-2">
                        "{item.text}"
                      </p>
                    </div>

                    <button
                      onClick={() => adoptSuggestion(item.text, item.targetPocId)}
                      className="self-end px-2.5 py-1 rounded-lg bg-cyan-500/10 hover:bg-cyan-500/20 text-cyan-300 border border-cyan-500/30 text-[11px] font-bold flex items-center gap-1 transition cursor-pointer"
                    >
                      <span>Cargar en Terminal</span>
                      <ArrowRight className="w-3 h-3" />
                    </button>
                  </div>
                ))}
              </div>
            </div>
          )}

          {/* SECTION 3: LIST OF MY CREATED POCS */}
          <div className="space-y-3 font-mono text-xs">
            <h4 className="text-slate-400 uppercase font-semibold text-xs flex items-center gap-2">
              <Flame className="w-4 h-4 text-amber-400" />
              <span>Mis Proof-of-Concepts Creados ({myCreatedPocs.length})</span>
            </h4>

            {myCreatedPocs.map((poc) => (
              <div
                key={poc.id}
                className="bg-slate-900/60 hover:bg-slate-900 border border-slate-800 rounded-2xl p-4 flex flex-col sm:flex-row sm:items-center justify-between gap-3 transition"
              >
                <div>
                  <div className="flex items-center gap-2">
                    <h5 className="font-bold text-white text-sm">{poc.title}</h5>
                    <span className="text-emerald-400 font-bold bg-emerald-500/10 px-1.5 py-0.5 rounded">
                      {poc.ticker}
                    </span>
                    <span className="text-slate-500 text-[11px]">
                      {poc.promptHistory.length} versiones desplegadas
                    </span>
                  </div>
                  <p className="text-slate-400 text-xs font-sans mt-0.5 max-w-xl line-clamp-1">
                    {poc.tagline}
                  </p>
                </div>

                <div className="flex items-center gap-3 shrink-0">
                  <div className="text-right">
                    <span className="text-white font-bold block">{poc.bondingCurveProgress.toFixed(1)}% Curva</span>
                    <span className="text-slate-400 text-[11px]">{poc.holdersCount} holders</span>
                  </div>

                  <button
                    onClick={() => {
                      setActivePoC(poc);
                      onClose();
                    }}
                    className="px-3 py-1.5 rounded-xl bg-slate-800 hover:bg-slate-700 text-white font-bold flex items-center gap-1 transition"
                  >
                    <Play className="w-3.5 h-3.5 fill-current" />
                    <span>Ver PoC</span>
                  </button>
                </div>
              </div>
            ))}
          </div>
        </div>
      </div>
    </div>
  );
};
